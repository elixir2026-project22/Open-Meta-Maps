"""Generate the Home and About pages. Single source of truth: run this module, commit the HTML.

  python3 layout_atlas/navigation.py

Counts and licences come from data/atlas_registry.json.
Overlap / unique-after-dedup counts come from docs/images/atlas/atlas_overlap.json when present.
Structure mirrors README: intro → data construction (Atlas) → layout optimisation → outputs / licensing.
"""
import html
import json
from pathlib import Path
from core import ROOT
import ui
REG = ROOT / 'data' / 'atlas_registry.json'
OVERLAP = ROOT / 'docs' / 'images' / 'atlas' / 'atlas_overlap.json'

def _registry():
    return json.loads(REG.read_text())

def _overlap():
    if OVERLAP.exists():
        return json.loads(OVERLAP.read_text())
    return None

def _fmt(n):
    return f'{int(n):,}'

HOME_CSS = '<style>.hero{padding:18px 0 8px}.hero h1{font-size:clamp(28px,5vw,44px)}.cta{display:inline-block;background:var(--accent);color:var(--accent-ink);padding:12px 26px;border-radius:999px;text-decoration:none;font-weight:600;font-size:17px;margin:6px 10px 6px 0}.cta.alt{background:var(--soft);color:var(--ink)}.steps3{display:grid;grid-template-columns:repeat(auto-fit,minmax(230px,1fr));gap:16px;margin:24px 0}.steps3 .card b{display:block;color:var(--accent);font-size:13px;letter-spacing:.06em;text-transform:uppercase}.steps3 .card h3{margin:4px 0}.fig{margin:12px 0 8px}.fig img{max-width:100%;height:auto;border:1px solid var(--line,#d0d7de);border-radius:8px}.fig .meta{margin-top:6px}</style>'
TOOL = 'layout_atlas/results/tool/index.html'
ATLAS = 'layout_atlas/results/atlas_browser/index.html'

def home():
    b = ui.bi
    steps = ''.join((f'<div class="card"><b>{n}</b><h3>{b(t)}</h3><p class="meta">{b(d)}</p></div>' for n, t, d in [('1', 'Choose a model', 'Upload an SBML (.xml) or BiGG/COBRA (.json) genome-scale model, or pick an example: e_coli_core, iIT341, iMM904 or iML1515.'), ('2', 'Generate', 'One click. Matched Atlas structures keep their curated geometry; every other reaction is completed with Bézier connections. All reactions and metabolites of your model are kept.'), ('3', 'Download', 'Get the complete map as editable SVG or Escher JSON, with per-reaction provenance and licence metadata.')]))
    body = HOME_CSS + f'<div class="hero"><a class="cta" href="{TOOL}">' + b('Open the Map Generator') + f'</a><a class="cta alt" href="{ATLAS}">' + b('Browse the Atlas') + f'</a><a class="cta alt" href="layout_atlas/results/about/index.html">' + b('About and data provenance') + '</a></div><div class="steps3">' + steps + '</div><div class="note">' + b('Result details report, for each reaction, whether its geometry was reused from a curated community map, guided by topology or EC, or generated by the algorithm. Atlas construction is described under About / Provenance. The Atlas Browser searches curated modules and downloads Escher JSON with a provenance/licence manifest.') + '</div>'
    lead =lead = b('Upload a genome-scale metabolic model and get a complete, readable and editable metabolic map, drawn from public community pathway layouts where they fit.')
    ui.write(ROOT / 'index.html', 'Open Meta Maps', body, section='home', lead=lead)

def about():
    e = html.escape
    b = ui.bi
    reg = _registry()
    ov = _overlap() or {}
    oc = reg['open_core']
    ext = reg['extensions']
    mods = oc['modules_with_extensions']
    total = sum(mods.values())
    core_sum = sum(oc['modules'].values())
    by_ov = (ov.get('by_source') or {})
    version = '0.3'
    try:
        version = str(json.loads((Path(__file__).parent / 'config.json').read_text()).get('version') or version)
    except Exception:
        pass

    def sec(t, inner):
        return f'<section class="panel"><h2>{b(t)}</h2>{inner}</section>'

    def row(*cells):
        return '<tr>' + ''.join((f'<td>{c}</td>' for c in cells)) + '</tr>'

    def uniq(key):
        return (by_ov.get(key) or {}).get('unique_reaction_sets')

    s1 = sec(
        'About Open Meta Maps',
        '<p><b>' + b('Two parts: a curated-structure Atlas from public community maps, and a layout optimisation pipeline that reuses matching geometry and completes the rest with Bézier connections.') + '</b></p><p>' + b('Open Meta Maps is ELIXIR BioHackathon Europe 2026 ') + '<a href="https://github.com/elixir2026-project22">' + b('Project 22') + '</a>' + b(' (Open Pathway Maps). Every reaction and metabolite of the uploaded GEM is drawn; stoichiometry and compartments are unchanged.') + '</p><p class="meta">' + b('Map Generator: python3 project.py tool or ./start_tool.command. Examples: e_coli_core, iIT341, iMM904, iML1515. Viewer: pan, wheel/pinch zoom, minimap. Server exits when the last tab closes (~8 s); --keep-running disables that. Evaluate layouts with python3 project.py evaluate.') + '</p>',
    )

    about_path = ROOT / 'layout_atlas' / 'results' / 'about' / 'index.html'
    overview_rel = ui.rel(about_path, 'docs/images/atlas/atlas_overview.png')
    examples_rel = ui.rel(about_path, 'docs/images/atlas/atlas_examples.svg')

    th = ''.join((f'<th>{b(h)}</th>' for h in ['Source', 'What is used', 'Modules', 'Unique after dedup', 'Licence']))
    dflt_u = lambda k: _fmt(uniq(k)) if uniq(k) is not None else '—'
    wp_mods = mods['wikipathways'] + mods['wikipathways_geometry']
    wp_u = None
    if uniq('wikipathways') is not None and uniq('wikipathways_geometry') is not None:
        wp_u = uniq('wikipathways') + uniq('wikipathways_geometry')
    tbl = '<div class="tablewrap"><table><thead><tr>' + th + '</tr></thead><tbody>'
    tbl += row('Escher', b(f"{oc['maps']['escher']} community maps"), _fmt(mods['escher']), dflt_u('escher'), 'CC0-1.0')
    tbl += row('Reactome', b(f"release 97 · {oc['maps']['reactome']} diagrams"), _fmt(mods['reactome']), dflt_u('reactome'), 'CC0 (data)')
    tbl += row('WikiPathways', b(f"release 20261110 · {oc['maps']['wikipathways']} maps; {_fmt(mods['wikipathways'])} semantic + {_fmt(mods['wikipathways_geometry'])} geometry-only"), _fmt(wp_mods), _fmt(wp_u) if wp_u is not None else '—', 'CC0-1.0')
    tbl += row('Human-maps', b(f"{ext['human_maps']['maps']} official Escher JSON maps"), _fmt(mods['human_maps']), dflt_u('human_maps'), 'CC BY 4.0')
    tbl += row('BRENDA', b(f"{ext['brenda']['pathways']} pathway maps; layout possibly automatic"), _fmt(mods['brenda']), dflt_u('brenda'), 'CC BY 4.0')
    tbl += row('Metabolism Regulation', b(f"{ext['metabolismregulation']['maps']} SBGN-ML gallery maps"), _fmt(mods['metabolismregulation']), dflt_u('metabolismregulation'), 'CC BY 4.0')
    tbl += row('PANTHER', b(f"version {ext['panther']['version']} · {ext['panther']['maps']} CellDesigner maps"), _fmt(mods['panther']), dflt_u('panther'), 'CC BY 4.0')
    tbl += row('iCH360', b(f"{ext['ich360']['maps']} custom Escher maps"), _fmt(mods.get('ich360', 0)), dflt_u('ich360'), 'MIT')
    tbl += '</tbody></table></div>'

    uniq_total = ov.get('unique_reaction_sets_global')
    stats = '<div class="stats">' + ui.stat(_fmt(total), 'cut modules (default Atlas)') + ui.stat(_fmt(uniq_total) if uniq_total is not None else '—', 'unique after dedup') + ui.stat(_fmt(core_sum), 'open-core SQLite modules') + '</div>'

    s_data = sec(
        '1. Data construction — the curated-structure Atlas',
        stats
        + '<div class="fig"><img src="' + e(overview_rel) + '" alt="' + b('Landscape overview mosaic of unique-after-dedup Atlas modules by source') + '" width="700"/><p class="meta">' + b('One tile per unique reaction set within each source; tile size scales with reaction count. Totals count cut windows, not independent drawings.') + '</p></div>'
        + '<h3>' + b('Sources and licences') + '</h3>' + tbl
        + '<p class="meta">' + b('WikiPathways semantic modules live in open_core.sqlite; geometry-only windows ship as an extension for repository size. Both load by default. Dedup stats: docs/images/atlas/atlas_overlap.json.') + '</p>'
        + '<p>' + b('The Atlas Browser tab searches these curated modules by EC, reaction, metabolite or model ID, source map and licence, and downloads selected modules as Escher JSON with a provenance/licence manifest (rebuild the search index with python3 tools/build_atlas_browser_index.py).') + '</p>'
        + '<p>' + b('python3 project.py data export bundles the whole Atlas into one archive: Escher JSON per module, the same manifest and the third-party notices (--source, --licence and --all-windows select a part).') + '</p>'
        + '<div class="fig"><img src="' + e(examples_rel) + '" alt="' + b('Example Atlas modules with captions') + '" width="700"/><p class="meta">' + b('Representative modules per source (source, map name, reaction count).') + '</p></div>'
        + '<h3>' + b('Extraction, identity and selection') + '</h3>'
        + '<ul>'
        + '<li><b>' + b('Cut') + '</b>: ' + b('in-repo Escher community cutter (parity-tested); Stage B diagram/geometry windows for Reactome, WikiPathways, Human-maps, Metabolism Regulation, PANTHER and iCH360; BRENDA’s own extractor.') + '</li>'
        + '<li><b>' + b('Deduplicate') + '</b>: ' + b('core families and geometric variants; Stage B near-nested dedupe (nest_factor=2).') + '</li>'
        + '<li><b>' + b('Canonical ids') + '</b>: ' + b('BiGG, MetaNetX and/or Rhea where a unique crosswalk exists.') + '</li>'
        + '<li><b>' + b('Provenance') + '</b>: ' + b('source, map, licence and an extraction block (method, version, parameters, counts).') + '</li>'
        + '<li><b>' + b('Selection') + '</b>: ' + b('coverage ranks first; among same-source biochemical matches with the same reaction set, the denser drawing is kept.') + '</li>'
        + '</ul>'
        + '<p class="meta">' + b('Worked examples: docs/atlas_data_management.md#worked-examples · data/README.md.') + '</p>',
    )

    s_layout = sec(
        '2. Layout optimisation algorithm',
        '<h3>' + b('Matching and curated reuse') + '</h3>'
        + '<p>' + b('Reactions are matched to Atlas modules (EC currentisation, Rhea metabolite scoring, name normalisation, weighted Jaccard, vicinity propagation). Report curated, topology-only and optional EC suggestions as separate rates in reaction_provenance.json. EC similarity extension is off by default (CLI --ec). Matched geometry is kept as drawn; the rest uses layout_style=curated (Bézier). Orthogonal libavoid remains CLI --layout-style legacy only. Details: docs/reaction_map_matching.md · docs/methodology.md.') + '</p>'
        + '<h3>' + b('Layout stages') + '</h3>'
        + '<p>' + b('After matching, the Composer keeps curated blocks rigid, completes uncovered reactions, orients free reactions, composes stray components, draws Bézier connections and places labels. Small models take the full path; mid-size models use a global plan then the same curated Bézier pass; larger models keep a skeleton and draw ~50-reaction views on demand. Full stage table: README §2.') + '</p>'
        + '<h3>' + b('Layout rules and evaluation') + '</h3>'
        + '<p>' + b('Rules (crossings, overlaps, long edges, participant consistency, compartments, compactness, reproducibility, scale): status table in README. Compose writes layout_quality into layout_issues.json / report.json; python3 project.py evaluate adds layout-rules metrics.') + '</p>'
        + '<ul>'
        + '<li>' + b('Optimised (partially): crossings and unrelated overlaps; detour and bends; long lines and cofactor clones; participant placement; curated-structure continuity; periphery, aspect, blank space.') + '</li>'
        + '<li>' + b('Not yet optimised: axis-aligned segments and axes; grid metabolites; chain turn angles; cycle placement; compartment packing.') + '</li>'
        + '<li>' + b('Build-on-previous: compose --previous map.json pins matched nodes; evaluate --compare-map measures displacement.') + '</li>'
        + '<li>' + b('Gaps: 2D component packing, harder orientation, compose --seed. Details: docs/layout_evaluation.md · docs/limitations.md.') + '</li>'
        + '</ul>',
    )

    s_out = sec(
        'Outputs',
        '<ul>'
        + '<li><b>' + b('Reaction provenance') + '</b>: ' + b('curated (community layout), topology-only suggestion, functional (EC) suggestion, bridge or generated, with matching evidence') + '</li>'
        + '<li><b>' + b('Layout quality') + '</b> · <b>' + b('Generation settings') + '</b> · <b>' + b('Licensing metadata') + '</b> (<code>licenses.json</code>)</li>'
        + '</ul>'
        + '<p>' + b('Integrity check: all reactions drawn; stoichiometry and compartments unchanged.') + '</p>'
        + '<p class="meta">' + b('Report files') + ': <code>report.json</code> · <code>reaction_provenance.json</code> · <code>licenses.json</code> · ' + b('Software version') + f': v{e(version)} · ' + b('Registry generated') + f': {e(reg.get("generated", ""))}</p>',
    )

    s_lic = sec(
        'Licensing',
        '<p>' + b('The software is MIT (LICENSE). The default Atlas mixes CC0, CC BY 4.0 and MIT (iCH360) sources; reuse must keep the attributions in THIRD_PARTY_NOTICES.md.') + '</p>',
    )

    cards = ''.join((f'<a class="card" href="{ui.rel(about_path, path)}" style="text-decoration:none"><h3>{b(en)}</h3></a>' for en, path in [('Installation', 'docs/installation.md'), ('Data sources', 'docs/data_sources.md'), ('Atlas data management', 'docs/atlas_data_management.md'), ('Reaction–map matching', 'docs/reaction_map_matching.md'), ('Methodology', 'docs/methodology.md'), ('Layout evaluation', 'docs/layout_evaluation.md'), ('Limitations', 'docs/limitations.md'), ('Third-party notices', 'THIRD_PARTY_NOTICES.md'), ('Atlas data layout', 'data/README.md')]))
    s_docs = sec('Documentation', '<div class="grid">' + cards + '</div>')
    d = ROOT / 'layout_atlas' / 'results' / 'about'
    d.mkdir(parents=True, exist_ok=True)
    ui.write(
        d / 'index.html',
        'About / Provenance',
        HOME_CSS + s1 + s_data + s_layout + s_out + s_lic + s_docs,
        section='about',
        lead=b('Curated-structure Atlas construction and layout optimisation for Open Meta Maps.'),
    )

def generate():
    home()
    about()
    return dict(status='generated', registry=str(REG.relative_to(ROOT)))
if __name__ == '__main__':
    print(generate())
